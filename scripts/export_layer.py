#!/usr/bin/env python3
"""Export one CONV_2D layer from the .tflite as a self-contained C test case.

Emits src/kernels/layer_data.h containing, as const C arrays:
  - the layer's exact INPUT activations (from running grace_hopper.jpg)
  - its weights [Cout, kh, kw, Cin], bias, and per-channel requantize
    params (M0, total right-shift = 31+rs), zero points
  - per-channel weight sums (for the hoisted zero-point correction)
  - the EXPECTED OUTPUT produced by TFLite itself -> the bare-metal kernel
    must reproduce it bit-for-bit.
The math mirrors scripts/ref_conv.py exactly — read that file's header first.
"""
import sys
import numpy as np
from PIL import Image
from ai_edge_litert.interpreter import Interpreter, OpResolverType

TARGET = sys.argv[1] if len(sys.argv) > 1 else "layer1_0_conv1"

def preprocess(path):
    img = Image.open(path).convert("RGB"); w, h = img.size
    s = 256 / min(w, h)
    img = img.resize((round(w*s), round(h*s)), Image.BILINEAR); w, h = img.size
    img = img.crop(((w-224)//2, (h-224)//2, (w-224)//2+224, (h-224)//2+224))
    x = np.asarray(img, np.float32) / 255.0
    x = (x - [0.485, 0.456, 0.406]) / [0.229, 0.224, 0.225]
    return x.transpose(2, 0, 1)[None]

ip = Interpreter(model_path="src/model/resnet18_int8_channelwise.tflite",
                 experimental_op_resolver_type=OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES,
                 experimental_preserve_all_tensors=True)
ip.allocate_tensors()
inp = ip.get_input_details()[0]
s_in, zp_in = inp['quantization']
x = preprocess("src/model/testdata/grace_hopper.jpg")
ip.set_tensor(inp['index'], np.clip(np.round(x/s_in)+zp_in, -128, 127).astype(np.int8))
ip.invoke()

tens = {t['index']: t for t in ip.get_tensor_details()}
op = next(o for o in ip._get_ops_details() if o['op_name'] == 'CONV_2D'
          and any(TARGET in tens[i]['name'] for i in o['inputs'] if i in tens))
ai, wi, bi = op['inputs'][:3]; oi = op['outputs'][0]
A = ip.get_tensor(ai)                       # int8 NHWC
W = ip.get_tensor(wi)                       # int8 [Cout,kh,kw,Cin]
B = ip.get_tensor(bi)                       # int32
Y = ip.get_tensor(oi)                       # int8 NHWC — the target
qa = tens[ai]['quantization_parameters']; qw = tens[wi]['quantization_parameters']
qo = tens[oi]['quantization_parameters']
sa, za = float(qa['scales'][0]), int(qa['zero_points'][0])
sw = qw['scales'].astype(np.float64)
so, zo = float(qo['scales'][0]), int(qo['zero_points'][0])

N, H, Wd, Cin = A.shape
Cout, kh, kw, _ = W.shape
Ho, Wo = Y.shape[1], Y.shape[2]
stride = (H + (1 if H % Ho else 0)) // Ho if Ho != H else 1
pt = max((Ho-1)*stride + kh - H, 0) // 2
pl = max((Wo-1)*stride + kw - Wd, 0) // 2

# Q31 fixed-point multiplier per channel (ref_conv.py explains the derivation).
mant, exp = np.frexp(sa * sw / so)
M0 = np.round(mant * (1 << 31)).astype(np.int64)
ovf = M0 == (1 << 31)
M0 = np.where(ovf, M0 >> 1, M0); exp = np.where(ovf, exp + 1, exp)
assert (exp <= 0).all(), "positive exponent not supported by the kernel"
shift_total = (31 - exp).astype(np.int64)        # single-round: >> (31 + rs)
wsum = W.reshape(Cout, -1).astype(np.int64).sum(axis=1)

def carr(name, ctype, arr):
    flat = np.asarray(arr).ravel()
    body = ",".join(str(int(v)) for v in flat)
    # aligned(8): X1 reads these byte arrays as packed 64-bit lanes (and
    # CV-Wally, unlike Spike, may not tolerate misaligned loads).
    return (f"static const {ctype} __attribute__((aligned(8))) "
            f"{name}[{flat.size}] = {{{body}}};\n")

with open("src/kernels/layer_data.h", "w") as f:
    f.write(f"""// GENERATED by scripts/export_layer.py — do not edit.
// Layer: {TARGET}   input {list(A.shape)}  weights {list(W.shape)}  output {list(Y.shape)}
// One complete, self-contained test case: run conv2d_b0() over L_INPUT with
// these params and the result must equal L_EXPECTED byte-for-byte.
#pragma once
#include <stdint.h>
#define L_H {H}
#define L_W {Wd}
#define L_CIN {Cin}
#define L_COUT {Cout}
#define L_KH {kh}
#define L_KW {kw}
#define L_STRIDE {stride}
#define L_PAD_T {pt}
#define L_PAD_L {pl}
#define L_HO {Ho}
#define L_WO {Wo}
#define L_ZA {za}
#define L_ZO {zo}
#define L_K ({kh}*{kw}*{Cin})
""")
    f.write(carr("L_INPUT",    "int8_t",  A))
    f.write(carr("L_WEIGHTS",  "int8_t",  W))
    f.write(carr("L_BIAS",     "int32_t", B))
    f.write(carr("L_M0",       "int32_t", M0))
    f.write(carr("L_SHIFT",    "int32_t", shift_total))
    f.write(carr("L_WSUM",     "int32_t", wsum))
    f.write(carr("L_EXPECTED", "int8_t",  Y))
print(f"exported {TARGET}: in {A.shape} -> out {Y.shape}, K={kh*kw*Cin}, "
      f"stride={stride} pad=({pt},{pl}), za={za} zo={zo}")
print(f"header size: ", end=""); import os; print(f"{os.path.getsize('src/kernels/layer_data.h')//1024} KB")
