#!/usr/bin/env python3
"""Export layer1.0 — ONE COMPLETE RESIDUAL BLOCK — as a C test case.

Emits src/kernels/block_data.h: the block input (= the skip operand), both
convs' weights/bias/packed-rq params, the ADD's multipliers, and TFLite's
recorded output after EVERY stage (conv1, conv2, add) so a failure localizes
to one kernel. Brief §5 coverage: "complete model inference or one complete
Transformer/CNN block" — this is that block.
"""
import numpy as np
from PIL import Image
from ai_edge_litert.interpreter import Interpreter, OpResolverType

def preprocess(p):
    img = Image.open(p).convert("RGB"); w,h = img.size
    s = 256/min(w,h); img = img.resize((round(w*s),round(h*s)), Image.BILINEAR); w,h = img.size
    img = img.crop(((w-224)//2,(h-224)//2,(w-224)//2+224,(h-224)//2+224))
    x = np.asarray(img,np.float32)/255.0
    x = (x-[0.485,0.456,0.406])/[0.229,0.224,0.225]
    return x.transpose(2,0,1)[None]

ip = Interpreter(model_path="src/model/resnet18_int8_channelwise.tflite",
                 experimental_op_resolver_type=OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES,
                 experimental_preserve_all_tensors=True)
ip.allocate_tensors()
inp = ip.get_input_details()[0]; s_in, zp_in = inp['quantization']
ip.set_tensor(inp['index'], np.clip(np.round(preprocess("src/model/testdata/grace_hopper.jpg")/s_in)+zp_in,-128,127).astype(np.int8))
ip.invoke()
tens = {t['index']: t for t in ip.get_tensor_details()}

def conv_bundle(target):
    op = next(o for o in ip._get_ops_details() if o['op_name']=='CONV_2D'
              and any(target in tens[i]['name'] for i in o['inputs'] if i in tens))
    ai, wi, bi = op['inputs'][:3]; oi = op['outputs'][0]
    A = ip.get_tensor(ai); W = ip.get_tensor(wi); B = ip.get_tensor(bi); Y = ip.get_tensor(oi)
    qa = tens[ai]['quantization_parameters']; qw = tens[wi]['quantization_parameters']
    qo = tens[oi]['quantization_parameters']
    sa, za = float(qa['scales'][0]), int(qa['zero_points'][0])
    sw = qw['scales'].astype(np.float64)
    so, zo = float(qo['scales'][0]), int(qo['zero_points'][0])
    mant, exp = np.frexp(sa*sw/so)
    M0 = np.round(mant*(1<<31)).astype(np.int64)
    ovf = M0==(1<<31); M0 = np.where(ovf,M0>>1,M0); exp = np.where(ovf,exp+1,exp)
    assert (exp<=0).all()
    rq = (M0.astype(np.uint64) | ((31-exp).astype(np.uint64)<<32)
          | (np.uint64(zo & 0xFF) << np.uint64(40)))
    wsum = W.reshape(W.shape[0],-1).astype(np.int64).sum(axis=1)
    return A, W, B, Y, za, rq, wsum

A1, W1, B1, Y1, za1, rq1, ws1 = conv_bundle("layer1_0_conv1")
A2, W2, B2, Y2, za2, rq2, ws2 = conv_bundle("layer1_0_conv2")
assert np.array_equal(A2, Y1)                      # conv2 input IS conv1 output

add = next(o for o in ip._get_ops_details() if o['op_name']=='ADD')
i1, i2 = add['inputs'][0], add['inputs'][1]; oi = add['outputs'][0]
# identify which operand is conv2-out vs the skip, by tensor identity
t1, t2 = ip.get_tensor(i1), ip.get_tensor(i2)
if np.array_equal(t1, Y2): main_i, skip_i = i1, i2
else:                      main_i, skip_i = i2, i1
assert np.array_equal(ip.get_tensor(main_i), Y2)
assert np.array_equal(ip.get_tensor(skip_i), A1)   # skip IS the block input
Yb = ip.get_tensor(oi)
def q_of(i):
    q = tens[i]['quantization_parameters']
    return float(q['scales'][0]), int(q['zero_points'][0])
sm, zm = q_of(main_i); ss, zs = q_of(skip_i); so, zob = q_of(oi)

LS = 20
tm = 2.0*max(sm, ss)
def qmult(x):
    mant, exp = np.frexp(x)
    q = int(np.floor(mant*(1<<31)+0.5)); e = int(exp)
    if q == (1<<31): q >>= 1; e += 1
    return q, e
mm, em = qmult(sm/tm); ms, es = qmult(ss/tm); mo, eo = qmult(tm/((1<<LS)*so))
assert em<=0 and es<=0 and eo<=0
rqo = mo | ((31-eo)<<32) | ((zob & 0xFF)<<40)      # output stage == one xrq

def carr(f, name, ctype, arr):
    flat = np.asarray(arr).ravel()
    body = ",".join(str(int(v)) for v in flat)
    f.write(f"static const {ctype} __attribute__((aligned(8))) {name}[{flat.size}] = {{{body}}};\n")
def carr_u64(f, name, arr):
    body = ",".join(f"0x{int(v):x}ULL" for v in np.asarray(arr).ravel())
    f.write(f"static const uint64_t __attribute__((aligned(8))) {name}[{len(arr)}] = {{{body}}};\n")

with open("src/kernels/block_data.h", "w") as f:
    f.write(f"""// GENERATED by scripts/export_block.py — do not edit.
// layer1.0: conv1 -> conv2 -> residual add (+fused relu). Stage outputs are
// TFLite's own, so each kernel is checked independently before the chain.
#pragma once
#include <stdint.h>
#define BK_H 56
#define BK_W 56
#define BK_C 64
#define BK_K 576
#define BK_ZA1 {za1}
#define BK_ZA2 {za2}
// quantized ADD constants (single-round semantics, EXPERIMENTS.md E8)
#define BK_ADD_LS {LS}
#define BK_ADD_ZM {zm}
#define BK_ADD_ZS {zs}
#define BK_ADD_MM {mm}
#define BK_ADD_SHM {31-em}
#define BK_ADD_MS {ms}
#define BK_ADD_SHS {31-es}
#define BK_ADD_RQO 0x{rqo:x}ULL
""")
    carr(f, "BK_IN", "int8_t", A1)
    carr(f, "BK_W1", "int8_t", W1); carr(f, "BK_B1", "int32_t", B1)
    carr(f, "BK_WS1", "int32_t", ws1); carr_u64(f, "BK_RQ1", rq1)
    carr(f, "BK_W2", "int8_t", W2); carr(f, "BK_B2", "int32_t", B2)
    carr(f, "BK_WS2", "int32_t", ws2); carr_u64(f, "BK_RQ2", rq2)
    carr(f, "BK_EXP1", "int8_t", Y1)
    carr(f, "BK_EXP2", "int8_t", Y2)
    carr(f, "BK_EXPB", "int8_t", Yb)
print(f"block exported: add scales main={sm:.5g}/zp{zm} skip={ss:.5g}/zp{zs} out={so:.5g}/zp{zob}")
